-- 3. Funciones RPC transaccionales

-- create_product
create or replace function public.create_product(
  p_id_categoria bigint,
  p_codigo_barras text,
  p_nombre text,
  p_descripcion text,
  p_precio_compra numeric,
  p_precio_venta numeric,
  p_stock_minimo integer,
  p_id_proveedor bigint,
  p_stock_inicial integer
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid();
  v_id bigint;
begin
  if v_actor is null or public.current_role() is distinct from 'administrator' then raise exception 'forbidden'; end if;
  if nullif(btrim(p_nombre),'') is null or p_precio_compra is null or p_precio_compra < 0
    or p_precio_venta is null or p_precio_venta < 0 or p_stock_minimo is null or p_stock_minimo < 0
    or p_stock_inicial is null or p_stock_inicial < 0 then raise exception 'invalid_product'; end if;
  insert into public.producto(id_categoria,codigo_barras,nombre,descripcion,precio_compra,precio_venta,stock,stock_minimo,id_proveedor,activo)
    values(p_id_categoria,nullif(btrim(p_codigo_barras),''),btrim(p_nombre),p_descripcion,p_precio_compra,p_precio_venta,0,p_stock_minimo,p_id_proveedor,true)
    returning id into v_id;
  if p_stock_inicial > 0 then
    update public.producto set stock = p_stock_inicial, updated_at = now() where id = v_id;
    insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad,motivo,stock_anterior,stock_nuevo,referencia)
      values(v_id,v_actor,'entrada',p_stock_inicial,'Initial stock',0,p_stock_inicial,v_id::text);
  end if;
  return v_id;
end $$;

revoke all on function public.create_product(bigint,text,text,text,numeric,numeric,integer,bigint,integer) from public, anon;
grant execute on function public.create_product(bigint,text,text,text,numeric,numeric,integer,bigint,integer) to authenticated;

-- create_expense
create or replace function public.create_expense(
  p_fecha date,
  p_tipo text,
  p_concepto text,
  p_monto numeric,
  p_comprobante text,
  p_beneficiario text,
  p_id_proveedor bigint
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid();
  v_id bigint;
begin
  if v_actor is null or public.current_role() is distinct from 'administrator' then raise exception 'forbidden'; end if;
  if p_monto is null or p_monto <= 0 or nullif(btrim(p_tipo),'') is null or nullif(btrim(p_concepto),'') is null then
    raise exception 'invalid_expense';
  end if;
  insert into public.egreso(fecha,tipo,concepto,monto,comprobante,beneficiario,id_proveedor,id_usuario)
    values(coalesce(p_fecha,current_date),btrim(p_tipo),btrim(p_concepto),p_monto,nullif(btrim(p_comprobante),''),nullif(btrim(p_beneficiario),''),p_id_proveedor,v_actor)
    returning id into v_id;
  return v_id;
end $$;

revoke all on function public.create_expense(date,text,text,numeric,text,text,bigint) from public, anon;
grant execute on function public.create_expense(date,text,text,numeric,text,text,bigint) to authenticated;

-- void_sale
create or replace function public.void_sale(p_id_venta bigint, p_motivo text)
returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid();
  v_estado text;
  v_item record;
begin
  if v_actor is null or public.current_role() is distinct from 'administrator' then raise exception 'forbidden'; end if;
  select estado into v_estado from public.venta where id = p_id_venta for update;
  if not found then raise exception 'sale_not_found'; end if;
  if v_estado <> 'completada' then raise exception 'sale_not_active'; end if;

  update public.venta set estado = 'anulada', motivo_anulacion = coalesce(nullif(btrim(p_motivo),''),'Sin motivo') where id = p_id_venta;

  for v_item in select id_producto, cantidad from public.detalle_venta where id_venta = p_id_venta loop
    update public.producto set stock = stock + v_item.cantidad, updated_at = now() where id = v_item.id_producto;
    insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad,motivo,stock_anterior,stock_nuevo,referencia)
      values(v_item.id_producto,v_actor,'entrada',v_item.cantidad,'Sale voided',0,v_item.cantidad,p_id_venta::text);
  end loop;

  delete from public.ingreso where id_venta = p_id_venta;
end $$;

revoke all on function public.void_sale(bigint,text) from public, anon;
grant execute on function public.void_sale(bigint,text) to authenticated;

