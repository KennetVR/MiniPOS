-- Migración Idempotente: RPCs y Contrato de Flujo de Trabajo MiniPOS
-- Este script se puede ejecutar múltiples veces sin fallar por objetos existentes.

-- 1. Perfiles y roles
alter table public.profiles
  add column if not exists username text,
  add column if not exists nombre text,
  add column if not exists estado boolean not null default true;

create or replace function public.current_role() returns public.app_role
language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = (select auth.uid()) and estado
$$;

drop policy if exists "read own profile" on public.profiles;
drop policy if exists "read own profile or administrator list" on public.profiles;
create policy "read own profile or administrator list" on public.profiles for select to authenticated
  using (id = (select auth.uid()) or public.current_role() = 'administrator');

drop policy if exists "administrator manages profiles" on public.profiles;
create policy "administrator manages profiles" on public.profiles for update to authenticated
  using (public.current_role() = 'administrator') with check (public.current_role() = 'administrator');

grant select on public.profiles to authenticated;
grant update (role,username,nombre,estado) on public.profiles to authenticated;

create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id,username,nombre)
    values(new.id, split_part(coalesce(new.email,''),'@',1), nullif(new.raw_user_meta_data->>'nombre',''))
    on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_auth_user();

