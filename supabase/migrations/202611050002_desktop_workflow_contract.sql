create or replace function public.void_sale(p_id_venta bigint, p_motivo text)
returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid();
  v_estado text;
  v_item record;
  v_old integer;
begin
  if v_actor is null or public.current_role() is distinct from 'administrator' then raise exception 'forbidden'; end if;
  if nullif(btrim(p_motivo),'') is null then raise exception 'invalid_void_reason'; end if;
  select estado into v_estado from public.venta where id = p_id_venta for update;
  if not found or v_estado <> 'completada' then raise exception 'sale_not_found_or_already_voided'; end if;
  for v_item in
    select id_producto,cantidad from public.detalle_venta where id_venta = p_id_venta order by id_producto
  loop
    select stock into v_old from public.producto where id = v_item.id_producto for update;
    if not found then raise exception 'product_not_found'; end if;
    update public.producto set stock = stock + v_item.cantidad, updated_at = now() where id = v_item.id_producto;
    insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad,motivo,stock_anterior,stock_nuevo,referencia)
      values(v_item.id_producto,v_actor,'ajuste',v_item.cantidad,'Void sale: ' || btrim(p_motivo),v_old,v_old + v_item.cantidad,p_id_venta::text);
  end loop;
  update public.venta set estado = 'anulada', motivo_anulacion = btrim(p_motivo), fecha_anulacion = now() where id = p_id_venta;
  update public.ingreso
    set referencia = concat_ws(' | ', nullif(referencia,''), 'Sale voided')
    where id_venta = p_id_venta;
end $$;

revoke all on function public.void_sale(bigint,text) from public, anon;
grant execute on function public.void_sale(bigint,text) to authenticated;
