create or replace function public.create_product(
  p_id_categoria bigint,
  p_codigo_barras text,
  p_nombre text,
  p_descripcion text,
  p_precio_compra numeric,
  p_precio_venta numeric,
  p_stock_minimo integer,
  p_id_proveedor bigint,
  p_stock_inicial integer
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid();
  v_id bigint;
begin
  if v_actor is null or public.current_role() is distinct from 'administrator' then raise exception 'forbidden'; end if;
  if nullif(btrim(p_nombre),'') is null or p_precio_compra is null or p_precio_compra < 0
    or p_precio_venta is null or p_precio_venta < 0 or p_stock_minimo is null or p_stock_minimo < 0
    or p_stock_inicial is null or p_stock_inicial < 0 then raise exception 'invalid_product'; end if;
  insert into public.producto(id_categoria,codigo_barras,nombre,descripcion,precio_compra,precio_venta,stock,stock_minimo,id_proveedor,activo)
    values(p_id_categoria,nullif(btrim(p_codigo_barras),''),btrim(p_nombre),p_descripcion,p_precio_compra,p_precio_venta,0,p_stock_minimo,p_id_proveedor,true)
    returning id into v_id;
  if p_stock_inicial > 0 then
    update public.producto set stock = p_stock_inicial, updated_at = now() where id = v_id;
    insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad,motivo,stock_anterior,stock_nuevo,referencia)
      values(v_id,v_actor,'entrada',p_stock_inicial,'Initial stock',0,p_stock_inicial,v_id::text);
  end if;
  return v_id;
end $$;

