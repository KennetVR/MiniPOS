create function public.create_inventory_receipt(p_id_proveedor bigint, p_numero_comprobante text, p_items jsonb)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare v_actor uuid := auth.uid(); v_id bigint; v_item jsonb; v_product bigint; v_qty integer; v_cost numeric;
begin
  if v_actor is null or public.current_role() <> 'administrator' then raise exception 'forbidden'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'items_required'; end if;
  insert into public.entrada_inventario(id_usuario,id_proveedor,numero_comprobante) values(v_actor,p_id_proveedor,p_numero_comprobante) returning id into v_id;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_product := (v_item->>'id_producto')::bigint; v_qty := (v_item->>'cantidad')::integer; v_cost := (v_item->>'precio_compra')::numeric;
    if v_qty <= 0 or v_cost < 0 then raise exception 'invalid_item'; end if;
    update public.producto set stock = stock + v_qty where id = v_product;
    if not found then raise exception 'product_not_found'; end if;
    insert into public.detalle_entrada(id_entrada,id_producto,cantidad,precio_compra) values(v_id,v_product,v_qty,v_cost);
    insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad) values(v_product,v_actor,'entrada',v_qty);
  end loop;
  return v_id;
end $$;

create function public.create_sale(p_detalles jsonb, p_forma_pago text, p_descuento numeric)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare v_actor uuid := auth.uid(); v_id bigint; v_item jsonb; v_product bigint; v_qty integer; v_price numeric; v_total numeric := 0;
begin
  if v_actor is null or public.current_role() not in ('administrator','seller') then raise exception 'forbidden'; end if;
  if jsonb_typeof(p_detalles) <> 'array' or jsonb_array_length(p_detalles) = 0 or p_descuento < 0 then raise exception 'invalid_sale'; end if;
  -- Acquire product locks in stable id order to avoid deadlocks for overlapping baskets.
  perform p.id from public.producto p where p.id in (select (x->>'id_producto')::bigint from jsonb_array_elements(p_detalles) x) order by p.id for update;
  for v_item in select value from jsonb_array_elements(p_detalles) loop
    v_product := (v_item->>'id_producto')::bigint; v_qty := (v_item->>'cantidad')::integer;
    if v_qty <= 0 then raise exception 'invalid_quantity'; end if;
    select precio_venta into v_price from public.producto where id = v_product and activo;
    if not found then raise exception 'product_not_found'; end if;
    v_total := v_total + v_price * v_qty;
  end loop;
  if p_descuento > v_total then raise exception 'invalid_discount'; end if;
  insert into public.venta(id_usuario,forma_pago,descuento,total) values(v_actor,p_forma_pago,p_descuento,v_total-p_descuento) returning id into v_id;
  for v_item in select value from jsonb_array_elements(p_detalles) loop
    v_product := (v_item->>'id_producto')::bigint; v_qty := (v_item->>'cantidad')::integer;
    update public.producto set stock = stock - v_qty where id = v_product and stock >= v_qty;
    if not found then raise exception 'insufficient_stock'; end if;
    select precio_venta into v_price from public.producto where id=v_product;
    insert into public.detalle_venta(id_venta,id_producto,cantidad,precio) values(v_id,v_product,v_qty,v_price);
    insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad) values(v_product,v_actor,'venta',-v_qty);
  end loop;
  return v_id;
end $$;

create function public.adjust_inventory(p_id_producto bigint, p_stock_real integer, p_motivo text)
returns void language plpgsql security invoker set search_path = '' as $$
declare v_actor uuid := auth.uid(); v_old integer;
begin
  if v_actor is null or public.current_role() <> 'administrator' then raise exception 'forbidden'; end if;
  if p_stock_real < 0 or nullif(btrim(p_motivo),'') is null then raise exception 'invalid_adjustment'; end if;
  select stock into v_old from public.producto where id=p_id_producto for update;
  if not found then raise exception 'product_not_found'; end if;
  update public.producto set stock=p_stock_real where id=p_id_producto;
  insert into public.movimiento_stock(id_producto,id_usuario,tipo,cantidad,motivo)
  values(p_id_producto,v_actor,'ajuste',p_stock_real-v_old,btrim(p_motivo));
end $$;

revoke all on function public.create_inventory_receipt(bigint,text,jsonb), public.create_sale(jsonb,text,numeric), public.adjust_inventory(bigint,integer,text) from public, anon;
grant execute on function public.create_inventory_receipt(bigint,text,jsonb), public.create_sale(jsonb,text,numeric), public.adjust_inventory(bigint,integer,text) to authenticated;
