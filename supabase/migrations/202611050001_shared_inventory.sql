create extension if not exists pgcrypto;

create type public.app_role as enum ('administrator', 'seller');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.app_role not null default 'seller',
  created_at timestamptz not null default now()
);

create function public.current_role() returns public.app_role
language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = (select auth.uid())
$$;

create table public.categoria (id bigint generated by default as identity primary key, nombre text not null, descripcion text);
create table public.proveedor (id bigint generated by default as identity primary key, nombre text not null);
create table public.producto (
  id bigint generated by default as identity primary key,
  id_categoria bigint references public.categoria(id),
  codigo_barras text unique,
  nombre text not null,
  precio_venta numeric(12,2) not null check (precio_venta >= 0),
  stock integer not null default 0 check (stock >= 0),
  activo boolean not null default true
);
create table public.venta (
  id bigint generated by default as identity primary key,
  id_usuario uuid not null references public.profiles(id),
  fecha timestamptz not null default now(),
  forma_pago text not null,
  descuento numeric(12,2) not null default 0 check (descuento >= 0),
  total numeric(12,2) not null check (total >= 0)
);
create table public.detalle_venta (
  id bigint generated by default as identity primary key,
  id_venta bigint not null references public.venta(id) on delete cascade,
  id_producto bigint not null references public.producto(id),
  cantidad integer not null check (cantidad > 0),
  precio numeric(12,2) not null check (precio >= 0)
);
create table public.entrada_inventario (
  id bigint generated by default as identity primary key,
  id_usuario uuid not null references public.profiles(id),
  id_proveedor bigint references public.proveedor(id),
  numero_comprobante text,
  fecha timestamptz not null default now()
);
create table public.detalle_entrada (
  id bigint generated by default as identity primary key,
  id_entrada bigint not null references public.entrada_inventario(id) on delete cascade,
  id_producto bigint not null references public.producto(id),
  cantidad integer not null check (cantidad > 0),
  precio_compra numeric(12,2) not null check (precio_compra >= 0)
);
create table public.movimiento_stock (
  id bigint generated by default as identity primary key,
  id_producto bigint not null references public.producto(id),
  id_usuario uuid not null references public.profiles(id),
  tipo text not null check (tipo in ('entrada','venta','ajuste')),
  cantidad integer not null,
  motivo text,
  fecha timestamptz not null default now()
);

